import io
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from app.schemas import BIReport

def generate_pdf_report(report: BIReport, output_stream):
    """
    Generates a beautifully styled corporate PDF report from BIReport data.
    Writes the PDF data directly to output_stream.
    """
    doc = SimpleDocTemplate(
        output_stream,
        pagesize=letter,
        rightMargin=54,
        leftMargin=54,
        topMargin=54,
        bottomMargin=54
    )
    
    # Custom Theme Colors
    primary_color = colors.HexColor("#312E81")    # Deep Indigo
    secondary_color = colors.HexColor("#4F46E5")  # Purple
    accent_color = colors.HexColor("#0891B2")     # Cyan
    dark_neutral = colors.HexColor("#1F2937")     # Dark Charcoal
    light_neutral = colors.HexColor("#F3F4F6")    # Soft Grey
    white = colors.white
    
    styles = getSampleStyleSheet()
    
    # Custom Typography Styles
    title_style = ParagraphStyle(
        'CoverTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=28,
        leading=34,
        textColor=primary_color,
        spaceAfter=15
    )
    
    subtitle_style = ParagraphStyle(
        'CoverSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=14,
        leading=18,
        textColor=secondary_color,
        spaceAfter=30
    )
    
    h1_style = ParagraphStyle(
        'SectionH1',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=18,
        leading=22,
        textColor=primary_color,
        spaceBefore=15,
        spaceAfter=10,
        keepWithNext=True
    )
    
    h2_style = ParagraphStyle(
        'SectionH2',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=16,
        textColor=secondary_color,
        spaceBefore=10,
        spaceAfter=6,
        keepWithNext=True
    )
    
    body_style = ParagraphStyle(
        'ReportBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=dark_neutral,
        spaceAfter=8
    )
    
    bullet_style = ParagraphStyle(
        'ReportBullet',
        parent=body_style,
        leftIndent=15,
        firstLineIndent=-10,
        spaceAfter=4
    )
    
    meta_style = ParagraphStyle(
        'MetaText',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#6B7280"),
        spaceAfter=20
    )
    
    table_cell_style = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=10,
        textColor=dark_neutral
    )
    
    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=10,
        textColor=white
    )

    story = []
    
    # -------------------------------------------------------------------------
    # COVER PAGE
    # -------------------------------------------------------------------------
    story.append(Spacer(1, 1.5 * inch))
    # Elegant geometric header block (simulated via tables)
    cover_header = Table([[""]], colWidths=[504], rowHeights=[10])
    cover_header.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), secondary_color),
        ('BOTTOMPADDING', (0,0), (-1,-1), 0),
        ('TOPPADDING', (0,0), (-1,-1), 0),
    ]))
    story.append(cover_header)
    story.append(Spacer(1, 15))
    
    story.append(Paragraph("AI Business Intelligence & Research Report", title_style))
    story.append(Paragraph(f"Corporate Intelligence Profile: {report.company_name}", subtitle_style))
    story.append(Spacer(1, 10))
    story.append(Paragraph(f"Generated on: {report.generated_at}", meta_style))
    story.append(Paragraph("Prepared by: AI Multi-Agent BI Platform", meta_style))
    
    story.append(Spacer(1, 2 * inch))
    story.append(Paragraph("CONFIDENTIALITY NOTICE: The information contained in this report is generated by autonomous AI agents based on public data sources and predictive models. It is intended for strategic decision-making and consulting evaluation.", ParagraphStyle('Conf', parent=body_style, fontSize=8, leading=10, textColor=colors.HexColor("#9CA3AF"))))
    story.append(PageBreak())
    
    # -------------------------------------------------------------------------
    # SECTION 1: EXECUTIVE BRIEF & CEO PITCH
    # -------------------------------------------------------------------------
    story.append(Paragraph("1. Executive Brief", h1_style))
    story.append(Paragraph(f"<b>Strategic Direction:</b> {report.executive_summary.headline}", h2_style))
    story.append(Paragraph(report.executive_summary.summary, body_style))
    story.append(Spacer(1, 10))
    
    story.append(Paragraph("Personalized Consultant Pitch to CEO", h2_style))
    # Styled blockquote for the pitch
    pitch_text = report.executive_summary.pitch.replace("\n", "<br/>")
    pitch_table = Table([[Paragraph(f"<i>{pitch_text}</i>", ParagraphStyle('PitchText', parent=body_style, fontSize=10, leading=14, textColor=colors.HexColor("#374151")))]], colWidths=[480])
    pitch_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F5F3FF")), # Soft purple background
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#DDD6FE")),
        ('LEFTPADDING', (0,0), (-1,-1), 15),
        ('RIGHTPADDING', (0,0), (-1,-1), 15),
        ('TOPPADDING', (0,0), (-1,-1), 12),
        ('BOTTOMPADDING', (0,0), (-1,-1), 12),
    ]))
    story.append(pitch_table)
    story.append(Spacer(1, 15))
    
    # -------------------------------------------------------------------------
    # SECTION 2: COMPANY OVERVIEW & NEWS
    # -------------------------------------------------------------------------
    story.append(Paragraph("2. Corporate Profile", h1_style))
    story.append(Paragraph(f"<b>Industry:</b> {report.overview.industry}", body_style))
    story.append(Paragraph(f"<b>Headquarters:</b> {report.overview.headquarters}", body_style))
    story.append(Paragraph(f"<b>Geographic Presence:</b> {report.overview.geographic_presence}", body_style))
    story.append(Paragraph(f"<b>Revenue:</b> {report.overview.revenue} | <b>Funding:</b> {report.overview.funding}", body_style))
    
    story.append(Spacer(1, 5))
    story.append(Paragraph("Key Leadership", h2_style))
    for exec_member in report.overview.key_executives:
        story.append(Paragraph(f"• {exec_member}", bullet_style))
        
    story.append(Spacer(1, 5))
    story.append(Paragraph("Products & Services", h2_style))
    for prod in report.overview.products_services:
        story.append(Paragraph(f"• {prod}", bullet_style))
        
    story.append(Spacer(1, 10))
    story.append(Paragraph("Recent Developments & News", h2_style))
    for item in report.news:
        news_title = f"<b>{item.title}</b>"
        if item.date:
            news_title += f" ({item.date})"
        story.append(Paragraph(news_title, body_style))
        story.append(Paragraph(item.summary, ParagraphStyle('NewsSum', parent=body_style, leftIndent=10, textColor=colors.HexColor("#4B5563"))))
        story.append(Spacer(1, 4))
        
    story.append(PageBreak())
    
    # -------------------------------------------------------------------------
    # SECTION 3: SWOT ANALYSIS & RISKS
    # -------------------------------------------------------------------------
    story.append(Paragraph("3. Strategic Risk & Opportunities Analysis (SWOT)", h1_style))
    
    # Grid Table for SWOT
    swot_data = [
        [
            Paragraph("<b>STRENGTHS</b>", ParagraphStyle('SWOTH', parent=body_style, textColor=colors.HexColor("#065F46"))),
            Paragraph("<b>WEAKNESSES</b>", ParagraphStyle('SWOTH2', parent=body_style, textColor=colors.HexColor("#991B1B")))
        ],
        [
            Paragraph("<br/>".join([f"• {s}" for s in report.swot.strengths]), table_cell_style),
            Paragraph("<br/>".join([f"• {w}" for w in report.swot.weaknesses]), table_cell_style)
        ],
        [
            Paragraph("<b>OPPORTUNITIES</b>", ParagraphStyle('SWOTH3', parent=body_style, textColor=colors.HexColor("#0369A1"))),
            Paragraph("<b>THREATS</b>", ParagraphStyle('SWOTH4', parent=body_style, textColor=colors.HexColor("#9A3412")))
        ],
        [
            Paragraph("<br/>".join([f"• {o}" for o in report.swot.opportunities]), table_cell_style),
            Paragraph("<br/>".join([f"• {t}" for t in report.swot.threats]), table_cell_style)
        ]
    ]
    
    swot_table = Table(swot_data, colWidths=[240, 240])
    swot_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (0,0), colors.HexColor("#D1FAE5")),
        ('BACKGROUND', (1,0), (1,0), colors.HexColor("#FEE2E2")),
        ('BACKGROUND', (0,2), (0,2), colors.HexColor("#E0F2FE")),
        ('BACKGROUND', (1,2), (1,2), colors.HexColor("#FFEDD5")),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#D1D5DB")),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor("#E5E7EB")),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('TOPPADDING', (0,0), (-1,-1), 8),
        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
        ('LEFTPADDING', (0,0), (-1,-1), 10),
        ('RIGHTPADDING', (0,0), (-1,-1), 10),
    ]))
    story.append(swot_table)
    story.append(Spacer(1, 15))
    
    # -------------------------------------------------------------------------
    # SECTION 4: COMPETITOR COMPARISON
    # -------------------------------------------------------------------------
    story.append(Paragraph("4. Competitor Landscape Comparison", h1_style))
    
    # Formulate Competitor Table
    comp_header = ["Company", "Revenue", "Employees", "Market Position", "Strengths", "Weaknesses"]
    comp_rows = [[Paragraph(f"<b>{h}</b>", table_header_style) for h in comp_header]]
    
    # First row is the subject company itself
    comp_rows.append([
        Paragraph(f"<b>{report.company_name} (Subject)</b>", table_cell_style),
        Paragraph(report.overview.revenue, table_cell_style),
        Paragraph("See Overview", table_cell_style),
        Paragraph("Leader", table_cell_style),
        Paragraph("<br/>".join([f"• {s[:35]}..." for s in report.swot.strengths[:2]]), table_cell_style),
        Paragraph("<br/>".join([f"• {w[:35]}..." for w in report.swot.weaknesses[:2]]), table_cell_style),
    ])
    
    for c in report.competitors:
        comp_rows.append([
            Paragraph(f"<b>{c.name}</b>", table_cell_style),
            Paragraph(c.revenue, table_cell_style),
            Paragraph(c.employees, table_cell_style),
            Paragraph(c.market_position, table_cell_style),
            Paragraph("<br/>".join([f"• {s[:35]}..." for s in c.strengths[:2]]), table_cell_style),
            Paragraph("<br/>".join([f"• {w[:35]}..." for w in c.weaknesses[:2]]), table_cell_style),
        ])
        
    comp_table = Table(comp_rows, colWidths=[90, 60, 65, 75, 107, 107])
    comp_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), primary_color),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [white, light_neutral]),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#D1D5DB")),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('LEFTPADDING', (0,0), (-1,-1), 5),
        ('RIGHTPADDING', (0,0), (-1,-1), 5),
    ]))
    story.append(comp_table)
    story.append(PageBreak())
    
    # -------------------------------------------------------------------------
    # SECTION 5: AI IMPLEMENTATION ROADMAP & ROI PREDICTIONS
    # -------------------------------------------------------------------------
    story.append(Paragraph("5. AI Implementation Opportunities", h1_style))
    story.append(Paragraph("The following customized digital transformation initiatives are proposed to address operational pain points and unlock new growth channels.", body_style))
    story.append(Spacer(1, 10))
    
    for idx, rec in enumerate(report.ai_recommendations):
        rec_story = []
        rec_title = f"Initiative {idx+1}: {rec.recommended_solution}"
        rec_story.append(Paragraph(rec_title, h2_style))
        
        # Detail Grid
        details = [
            [Paragraph("<b>Problem:</b>", table_cell_style), Paragraph(rec.problem, table_cell_style)],
            [Paragraph("<b>Evidence:</b>", table_cell_style), Paragraph(rec.evidence, table_cell_style)],
            [Paragraph("<b>Reasoning:</b>", table_cell_style), Paragraph(rec.reasoning, table_cell_style)],
            [Paragraph("<b>Expected Benefits:</b>", table_cell_style), Paragraph(rec.expected_benefits, table_cell_style)],
            [Paragraph("<b>Difficulty:</b>", table_cell_style), Paragraph(f"{rec.implementation_difficulty} (Timeline: {rec.timeline})", table_cell_style)],
            [Paragraph("<b>Cost & ROI:</b>", table_cell_style), Paragraph(f"Cost: {rec.estimated_cost} | ROI: {rec.expected_roi} | Priority: {rec.priority}", table_cell_style)]
        ]
        
        detail_table = Table(details, colWidths=[120, 364])
        detail_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (0,-1), colors.HexColor("#EEF2F6")),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#E2E8F0")),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('TOPPADDING', (0,0), (-1,-1), 5),
            ('BOTTOMPADDING', (0,0), (-1,-1), 5),
            ('LEFTPADDING', (0,0), (-1,-1), 8),
            ('RIGHTPADDING', (0,0), (-1,-1), 8),
        ]))
        
        rec_story.append(detail_table)
        rec_story.append(Spacer(1, 15))
        
        story.append(KeepTogether(rec_story))
        
    # Build Document
    doc.build(story)
