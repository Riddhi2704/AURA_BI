import io
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from app.schemas import BIReport

def generate_ppt_report(report: BIReport, output_stream):
    """
    Generates a dark-themed corporate PowerPoint slide deck from BIReport data.
    Writes the PPTX data directly to output_stream.
    """
    prs = Presentation()
    
    # Slide Dimensions: 16:9 widescreen
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    
    # Premium Color Palette
    bg_color = RGBColor(3, 7, 18)        # Dark Indigo (#030712)
    card_color = RGBColor(17, 24, 39)    # Gray-900 (#111827)
    primary_color = RGBColor(99, 102, 241) # Indigo (#6366F1)
    accent_color = RGBColor(6, 182, 212)  # Cyan (#06B6D4)
    white_text = RGBColor(243, 244, 246)  # Off-white (#F3F4F6)
    muted_text = RGBColor(156, 163, 175)  # Muted Gray (#9CA3AF)
    
    # Helper: Set dark background for a slide
    def set_dark_bg(slide):
        background = slide.background
        fill = background.fill
        fill.solid()
        fill.fore_color.rgb = bg_color

    # Helper: Add Slide Title
    def add_slide_header(slide, title_text):
        title_box = slide.shapes.add_textbox(Inches(0.5), Inches(0.4), Inches(12.33), Inches(0.8))
        tf = title_box.text_frame
        tf.word_wrap = True
        tf.margin_left = tf.margin_top = tf.margin_right = tf.margin_bottom = 0
        
        p = tf.paragraphs[0]
        p.text = title_text.upper()
        p.font.name = "Arial"
        p.font.size = Pt(24)
        p.font.bold = True
        p.font.color.rgb = primary_color
        
        # Underline accent line
        line = slide.shapes.add_shape(
            1, # Rectangle
            Inches(0.5), Inches(1.1), Inches(2.0), Inches(0.04)
        )
        line.fill.solid()
        line.fill.fore_color.rgb = accent_color
        line.line.color.rgb = accent_color

    # -------------------------------------------------------------------------
    # SLIDE 1: TITLE SLIDE
    # -------------------------------------------------------------------------
    slide_layout = prs.slide_layouts[6] # Blank layout
    slide = prs.slides.add_slide(slide_layout)
    set_dark_bg(slide)
    
    # Large Title Box
    title_box = slide.shapes.add_textbox(Inches(1.0), Inches(2.2), Inches(11.33), Inches(3.0))
    tf = title_box.text_frame
    tf.word_wrap = True
    
    p = tf.paragraphs[0]
    p.text = "BUSINESS INTELLIGENCE & AI ROADMAP"
    p.font.name = "Arial"
    p.font.size = Pt(36)
    p.font.bold = True
    p.font.color.rgb = white_text
    
    p2 = tf.add_paragraph()
    p2.text = f"Strategic Profile: {report.company_name}"
    p2.font.name = "Arial"
    p2.font.size = Pt(22)
    p2.font.bold = True
    p2.font.color.rgb = accent_color
    p2.space_before = Pt(10)
    
    p3 = tf.add_paragraph()
    p3.text = f"Generated by Multi-Agent Consultant | {report.generated_at}"
    p3.font.name = "Arial"
    p3.font.size = Pt(14)
    p3.font.color.rgb = muted_text
    p3.space_before = Pt(40)

    # -------------------------------------------------------------------------
    # SLIDE 2: EXECUTIVE SUMMARY & CEO PITCH
    # -------------------------------------------------------------------------
    slide = prs.slides.add_slide(slide_layout)
    set_dark_bg(slide)
    add_slide_header(slide, "Executive Summary & CEO Brief")
    
    # Left Column: Summary
    left_box = slide.shapes.add_textbox(Inches(0.5), Inches(1.6), Inches(6.0), Inches(5.0))
    ltf = left_box.text_frame
    ltf.word_wrap = True
    
    lp1 = ltf.paragraphs[0]
    lp1.text = "Strategic Overview"
    lp1.font.name = "Arial"
    lp1.font.size = Pt(18)
    lp1.font.bold = True
    lp1.font.color.rgb = accent_color
    
    lp2 = ltf.add_paragraph()
    lp2.text = report.executive_summary.summary
    lp2.font.name = "Arial"
    lp2.font.size = Pt(13)
    lp2.font.color.rgb = white_text
    lp2.space_before = Pt(10)
    
    # Right Column: Pitch Card
    card = slide.shapes.add_shape(
        1, # Rectangle
        Inches(7.0), Inches(1.6), Inches(5.8), Inches(5.0)
    )
    card.fill.solid()
    card.fill.fore_color.rgb = card_color
    card.line.color.rgb = primary_color
    card.line.width = Pt(1.5)
    
    rtf = card.text_frame
    rtf.word_wrap = True
    rtf.margin_left = rtf.margin_top = rtf.margin_right = rtf.margin_bottom = Inches(0.3)
    
    rp1 = rtf.paragraphs[0]
    rp1.text = "CEO Pitch Memo"
    rp1.font.name = "Arial"
    rp1.font.size = Pt(16)
    rp1.font.bold = True
    rp1.font.color.rgb = primary_color
    
    rp2 = rtf.add_paragraph()
    # Format and cap pitch text to fit container
    pitch_clean = report.executive_summary.pitch
    if len(pitch_clean) > 550:
        pitch_clean = pitch_clean[:550] + "..."
    rp2.text = pitch_clean
    rp2.font.name = "Arial"
    rp2.font.size = Pt(11)
    rp2.font.color.rgb = white_text
    rp2.font.italic = True
    rp2.space_before = Pt(8)

    # -------------------------------------------------------------------------
    # SLIDE 3: CORPORATE PROFILE
    # -------------------------------------------------------------------------
    slide = prs.slides.add_slide(slide_layout)
    set_dark_bg(slide)
    add_slide_header(slide, "Corporate Profile")
    
    # Left Column: Overview Details
    details_box = slide.shapes.add_textbox(Inches(0.5), Inches(1.6), Inches(6.0), Inches(5.0))
    dtf = details_box.text_frame
    dtf.word_wrap = True
    
    dp1 = dtf.paragraphs[0]
    dp1.text = "Company Profile Details"
    dp1.font.name = "Arial"
    dp1.font.size = Pt(18)
    dp1.font.bold = True
    dp1.font.color.rgb = accent_color
    
    bullets = [
        f"Industry: {report.overview.industry}",
        f"Headquarters: {report.overview.headquarters}",
        f"Geographic Presence: {report.overview.geographic_presence}",
        f"Revenue: {report.overview.revenue}",
        f"Funding: {report.overview.funding}"
    ]
    for b in bullets:
        bp = dtf.add_paragraph()
        bp.text = f"• {b}"
        bp.font.name = "Arial"
        bp.font.size = Pt(14)
        bp.font.color.rgb = white_text
        bp.space_before = Pt(8)
        
    # Right Column: Products & Leadership
    right_box = slide.shapes.add_textbox(Inches(7.0), Inches(1.6), Inches(5.8), Inches(5.0))
    rtf_box = right_box.text_frame
    rtf_box.word_wrap = True
    
    rp_head = rtf_box.paragraphs[0]
    rp_head.text = "Main Products & Services"
    rp_head.font.name = "Arial"
    rp_head.font.size = Pt(16)
    rp_head.font.bold = True
    rp_head.font.color.rgb = accent_color
    
    for prod in report.overview.products_services[:4]:
        p_bp = rtf_box.add_paragraph()
        p_bp.text = f"• {prod}"
        p_bp.font.name = "Arial"
        p_bp.font.size = Pt(13)
        p_bp.font.color.rgb = white_text
        p_bp.space_before = Pt(4)
        
    exec_head = rtf_box.add_paragraph()
    exec_head.text = "Key Executives"
    exec_head.font.name = "Arial"
    exec_head.font.size = Pt(16)
    exec_head.font.bold = True
    exec_head.font.color.rgb = accent_color
    exec_head.space_before = Pt(15)
    
    for exec_member in report.overview.key_executives[:4]:
        e_bp = rtf_box.add_paragraph()
        e_bp.text = f"• {exec_member}"
        e_bp.font.name = "Arial"
        e_bp.font.size = Pt(13)
        e_bp.font.color.rgb = white_text
        e_bp.space_before = Pt(4)

    # -------------------------------------------------------------------------
    # SLIDE 4: SWOT ANALYSIS
    # -------------------------------------------------------------------------
    slide = prs.slides.add_slide(slide_layout)
    set_dark_bg(slide)
    add_slide_header(slide, "Strategic SWOT Analysis")
    
    # 4 Quadrants
    quad_w = Inches(5.9)
    quad_h = Inches(2.2)
    
    swot_configs = [
        ("Strengths", report.swot.strengths, Inches(0.5), Inches(1.6), RGBColor(16, 185, 129)),
        ("Weaknesses", report.swot.weaknesses, Inches(6.9), Inches(1.6), RGBColor(239, 68, 68)),
        ("Opportunities", report.swot.opportunities, Inches(0.5), Inches(4.3), RGBColor(59, 130, 246)),
        ("Threats", report.swot.threats, Inches(6.9), Inches(4.3), RGBColor(245, 158, 11))
    ]
    
    for title, items, left, top, color in swot_configs:
        card = slide.shapes.add_shape(1, left, top, quad_w, quad_h)
        card.fill.solid()
        card.fill.fore_color.rgb = card_color
        card.line.color.rgb = color
        card.line.width = Pt(1.5)
        
        ctf = card.text_frame
        ctf.word_wrap = True
        ctf.margin_left = ctf.margin_top = ctf.margin_right = ctf.margin_bottom = Inches(0.2)
        
        cp1 = ctf.paragraphs[0]
        cp1.text = title.upper()
        cp1.font.name = "Arial"
        cp1.font.size = Pt(14)
        cp1.font.bold = True
        cp1.font.color.rgb = color
        
        # Combine bullets
        bullet_text = "\n".join([f"• {item}" for item in items[:2]])
        cp2 = ctf.add_paragraph()
        cp2.text = bullet_text
        cp2.font.name = "Arial"
        cp2.font.size = Pt(10)
        cp2.font.color.rgb = white_text
        cp2.space_before = Pt(4)

    # -------------------------------------------------------------------------
    # SLIDE 5: COMPETITOR LANDSCAPE
    # -------------------------------------------------------------------------
    slide = prs.slides.add_slide(slide_layout)
    set_dark_bg(slide)
    add_slide_header(slide, "Competitor Landscape Matrix")
    
    # PowerPoint Table
    rows = len(report.competitors) + 2  # header + company + competitors
    cols = 6
    left = Inches(0.5)
    top = Inches(1.8)
    width = Inches(12.33)
    height = Inches(4.5)
    
    table_shape = slide.shapes.add_table(rows, cols, left, top, width, height)
    table = table_shape.table
    
    # Headers
    headers = ["Company", "Revenue", "Employees", "Market Position", "Strengths", "Weaknesses"]
    for col_idx, text in enumerate(headers):
        cell = table.cell(0, col_idx)
        cell.fill.solid()
        cell.fill.fore_color.rgb = primary_color
        p = cell.text_frame.paragraphs[0]
        p.text = text
        p.font.name = "Arial"
        p.font.size = Pt(12)
        p.font.bold = True
        p.font.color.rgb = white_text
        p.alignment = PP_ALIGN.CENTER
        
    # Company Row
    comp_row = [
        f"{report.company_name} (Subject)",
        report.overview.revenue,
        "Overview",
        "Leader",
        ", ".join(report.swot.strengths[:2]),
        ", ".join(report.swot.weaknesses[:2])
    ]
    for col_idx, text in enumerate(comp_row):
        cell = table.cell(1, col_idx)
        cell.fill.solid()
        cell.fill.fore_color.rgb = RGBColor(30, 27, 75) # Dark Blue accent
        p = cell.text_frame.paragraphs[0]
        p.text = text
        p.font.name = "Arial"
        p.font.size = Pt(10)
        p.font.color.rgb = white_text
        
    # Competitor Rows
    for row_idx, comp in enumerate(report.competitors):
        comp_data = [
            comp.name,
            comp.revenue,
            comp.employees,
            comp.market_position,
            ", ".join(comp.strengths[:2]),
            ", ".join(comp.weaknesses[:2])
        ]
        for col_idx, text in enumerate(comp_data):
            cell = table.cell(row_idx + 2, col_idx)
            cell.fill.solid()
            cell.fill.fore_color.rgb = card_color
            p = cell.text_frame.paragraphs[0]
            p.text = text
            p.font.name = "Arial"
            p.font.size = Pt(10)
            p.font.color.rgb = white_text

    # -------------------------------------------------------------------------
    # SLIDE 6: AI RECOMMENDATION MATRIX
    # -------------------------------------------------------------------------
    slide = prs.slides.add_slide(slide_layout)
    set_dark_bg(slide)
    add_slide_header(slide, "Proposed AI Opportunities")
    
    # Display 3 opportunities in side-by-side vertical cards
    card_w = Inches(3.8)
    card_h = Inches(4.8)
    gap = Inches(0.4)
    start_left = Inches(0.5)
    
    for idx, rec in enumerate(report.ai_recommendations[:3]):
        left = start_left + idx * (card_w + gap)
        top = Inches(1.6)
        
        card = slide.shapes.add_shape(1, left, top, card_w, card_h)
        card.fill.solid()
        card.fill.fore_color.rgb = card_color
        card.line.color.rgb = accent_color
        card.line.width = Pt(1.5)
        
        ctf = card.text_frame
        ctf.word_wrap = True
        ctf.margin_left = ctf.margin_top = ctf.margin_right = ctf.margin_bottom = Inches(0.2)
        
        cp1 = ctf.paragraphs[0]
        cp1.text = f"OPPORTUNITY {idx+1}"
        cp1.font.name = "Arial"
        cp1.font.size = Pt(12)
        cp1.font.bold = True
        cp1.font.color.rgb = primary_color
        
        cp2 = ctf.add_paragraph()
        cp2.text = rec.recommended_solution
        cp2.font.name = "Arial"
        cp2.font.size = Pt(14)
        cp2.font.bold = True
        cp2.font.color.rgb = accent_color
        cp2.space_before = Pt(4)
        
        fields = [
            f"Problem: {rec.problem[:90]}...",
            f"Benefits: {rec.expected_benefits}",
            f"Timeline: {rec.timeline}",
            f"Cost: {rec.estimated_cost}",
            f"Est. ROI: {rec.expected_roi}",
            f"Priority: {rec.priority}"
        ]
        
        for f in fields:
            p = ctf.add_paragraph()
            p.text = f
            p.font.name = "Arial"
            p.font.size = Pt(9.5)
            p.font.color.rgb = white_text
            p.space_before = Pt(6)
            
    # Save presentation
    prs.save(output_stream)
